// File storage on local disk (the VM's free block volume). Signed, expiring URLs; images re-encoded.
import { createHmac, createHash, randomBytes, timingSafeEqual } from 'node:crypto';
import { createReadStream, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { config } from './config.ts';

export const MAX_FILE = 500 * 1024 * 1024; // 500 MB for everyone
export const USER_QUOTA = 5 * 1024 * 1024 * 1024; // 5 GB per user (the disk is 200 GB)
const URL_TTL_S = 7 * 24 * 3600;

let signKey: Buffer | null = null;
function key() {
  if (signKey) return signKey;
  const env = process.env.FILES_SIGNING_KEY;
  if (env) signKey = Buffer.from(env, 'base64');
  else {
    const f = join(config.dataDir, 'files.key');
    if (existsSync(f)) signKey = readFileSync(f);
    else {
      mkdirSync(config.dataDir, { recursive: true });
      signKey = randomBytes(32);
      writeFileSync(f, signKey, { mode: 0o600 });
    }
  }
  return signKey;
}

export const filesRoot = () => join(config.dataDir, 'files');
export function pathFor(storageKey: string) {
  // keys are generated by us ("yyyy/mm/<uuid>"); still refuse anything that could walk out of the folder
  if (!/^\d{4}\/\d{2}\/[0-9a-f-]{36}$/.test(storageKey)) throw new Error('bad key');
  return join(filesRoot(), storageKey);
}
export function newKey(id: string) {
  const d = new Date();
  return `${d.getUTCFullYear()}/${String(d.getUTCMonth() + 1).padStart(2, '0')}/${id}`;
}

export async function saveBytes(storageKey: string, data: Buffer) {
  const p = pathFor(storageKey);
  mkdirSync(join(p, '..'), { recursive: true });
  await writeFile(p, data, { mode: 0o640 });
}
export const removeBytes = (storageKey: string) => rm(pathFor(storageKey), { force: true });
export const readStream = (storageKey: string) => createReadStream(pathFor(storageKey));
export const sizeOf = (storageKey: string) => statSync(pathFor(storageKey)).size;
export const sha256 = (b: Buffer) => createHash('sha256').update(b).digest();

const sig = (id: string, exp: number) => createHmac('sha256', key()).update(`${id}.${exp}`).digest('base64url');

/** URL the client can load directly (no auth header needed for <img>). */
export function signedUrl(base: string, id: string, ttl = URL_TTL_S) {
  const exp = Math.floor(Date.now() / 1000) + ttl;
  return `${base}/files/${id}?exp=${exp}&sig=${sig(id, exp)}`;
}
export function verifySig(id: string, exp: string, s: string) {
  const e = Number(exp);
  if (!Number.isFinite(e) || e < Date.now() / 1000) return false;
  const want = Buffer.from(sig(id, e));
  const got = Buffer.from(String(s));
  return want.length === got.length && timingSafeEqual(want, got);
}

export const PUBLIC_BASE = () => process.env.PUBLIC_URL ?? `http://${config.host}:${config.port}`;
