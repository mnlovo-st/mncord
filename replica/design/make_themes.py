"""Builds tokens.light.json, tokens.amoled.json and tokens.css from tokens.json (midnight)."""
import json, copy, pathlib
here = pathlib.Path(__file__).parent
base = json.loads((here / "tokens.json").read_text(encoding="utf-8"))
# accent used as text gets its own role so light theme can darken it
base["color"].setdefault("accent-text", base["color"]["accent"])
base["pairs"] = [p for p in base["pairs"] if p[:2] not in (["accent","bg"],["accent","surface"])]
base["pairs"] += [["accent-text","bg"],["accent-text","surface"]]
seen=[]
for pr in base["pairs"]:
    if pr not in seen: seen.append(pr)
base["pairs"]=seen
(here / "tokens.json").write_text(json.dumps(base, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

light = {
 "bg-deep":"#e2e6ee","bg":"#ffffff","surface":"#f2f4f8","surface-raised":"#ffffff","surface-hover":"#e7ebf2",
 "surface-selected":"#d8dfeb","surface-input":"#eceff4","popover":"#ffffff","border":"#d4dae5","border-input":"#7b879c",
 "text":"#111622","text-muted":"#465166","text-faint":"#5a667b","text-link":"#1858c8",
 "accent":"#4f57d9","accent-hover":"#434bc4","on-accent":"#ffffff","accent-text":"#3a41b8",
 "chrome":"#2a3446","on-chrome":"#f2f4f8",
 "danger":"#d9363c","danger-text":"#b4232a","on-danger":"#ffffff","danger-solid":"#c42f35",
 "success":"#16794a","success-solid":"#1a7a4b","on-success":"#ffffff","warning":"#9a5b00",
 "status-online":"#178a48","status-idle":"#a86f00","status-dnd":"#d9363c","status-offline":"#747f94","status-streaming":"#7c4dff",
 "mention-bg":"#fdf3d9","focus-ring":"#1858c8"}
amoled = {
 "bg-deep":"#000000","bg":"#000000","surface":"#05070a","surface-raised":"#0c0f16","surface-hover":"#151a26",
 "surface-selected":"#1d2436","surface-input":"#090b10","popover":"#07090d","border":"#1a2030","mention-bg":"#1f1b0e"}
out = {}
for name, over in (("light", light), ("amoled", amoled)):
    t = copy.deepcopy(base); t["_about"] = f"mncord theme '{name}' (overrides of midnight)."
    t["color"].update(over)
    (here / f"tokens.{name}.json").write_text(json.dumps(t, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    out[name] = t

def block(sel, colors):
    return sel + " {\n" + "".join(f"  --c-{k}: {v};\n" for k, v in colors.items()) + "}\n"
css = ["/* GENERATED by replica/design/make_themes.py, do not edit by hand. (c) mnlovo */\n"]
css.append(block(":root, [data-theme=\"midnight\"]", base["color"]))
css.append("  :root { color-scheme: dark; }\n")
css.append(block("[data-theme=\"light\"]", out["light"]["color"]).replace("}\n", "  color-scheme: light;\n}\n"))
css.append(block("[data-theme=\"amoled\"]", out["amoled"]["color"]))
v = [":root {\n"]
for k, f in base["font"].items():
    if not k.startswith("_"): v.append(f"  --font-{k}: {f};\n")
for k, ty in base["type"].items():
    if k.startswith("_"): continue
    v.append(f"  --text-{k}: {ty['size']}px; --leading-{k}: {ty['line']}px; --weight-{k}: {ty['weight']};\n")
for k, r in base["radius"].items(): v.append(f"  --radius-{k}: {r}px;\n")
for k, s in base["shadow"].items(): v.append(f"  --shadow-{k}: {s};\n")
for k, m in base["motion"].items():
    if not k.startswith("_"): v.append(f"  --motion-{k}: {m};\n")
for k, l in base["layout"].items():
    if isinstance(l, int): v.append(f"  --size-{k}: {l}px;\n")
v.append("}\n")
v.append(":root:lang(ar) { --font-sans: var(--font-arabic); }\n")
v.append("@media (prefers-reduced-motion: reduce) { :root { --motion-fast: 0ms; --motion-base: 0ms; --motion-slow: 0ms; } }\n")
v.append("[data-reduced-motion=\"true\"] { --motion-fast: 0ms; --motion-base: 0ms; --motion-slow: 0ms; }\n")
css += v
(here / "tokens.css").write_text("".join(css), encoding="utf-8")
app = here.parent.parent / "apps/desktop/src/renderer/styles/tokens.css"
app.parent.mkdir(parents=True, exist_ok=True)
app.write_text("".join(css), encoding="utf-8")
print("ok")
